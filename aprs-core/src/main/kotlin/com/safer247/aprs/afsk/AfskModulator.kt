package com.safer247.aprs.afsk

import com.safer247.aprs.protocol.EncodedTxPacket
import sivantoledo.ax25.Afsk1200Modulator
import sivantoledo.ax25.Packet

/**
 * Bell 202 AFSK-1200 modulator wrapping `javAX25`'s [Afsk1200Modulator].
 *
 * Accepts raw AX.25 UI frames without CRC/FCS (from `AprsTx.encodePacket().ax25Bytes`),
 * appends CRC-CCITT via `sivantoledo.ax25.Packet`, and produces mono AFSK PCM audio
 * as either signed 16-bit PCM ([ShortArray]) or normalized floats ([FloatArray]).
 */
class AfskModulator(
    val sampleRate: Int = AfskConfig.SAMPLE_RATE_HZ,
    txDelayUnits: Int = AfskConfig.TX_DELAY_UNITS,
    txTailUnits: Int = AfskConfig.TX_TAIL_UNITS
) {
    companion object {
        /** Max raw AX.25 frame bytes without CRC (`javAX25` `Packet.MAX_FRAME_SIZE` is 330 incl. 2-byte CRC). */
        const val MAX_AX25_BYTES_WITHOUT_CRC: Int = 328
    }

    private val modulator = Afsk1200Modulator(sampleRate)

    init {
        setTxDelay(txDelayUnits)
        setTxTail(txTailUnits)
    }

    /** Sets the preamble length in 10 ms units (e.g., `60` = 600 ms of `0x7E` flags).
     * @Synchronized ensures thread safety when modifying the modulator's state.
     * */
    @Synchronized
    fun setTxDelay(units: Int) {
        require(units >= 0) { "txDelayUnits must be >= 0 (got $units)." }
        modulator.setTxDelay(units)
    }

    /** Sets the trailer length in 10 ms units (`0` uses `javAX25`'s default 2 trailing `0x7E` flags).
     * @Synchronized ensures thread safety when modifying the modulator's state.
     * */
    @Synchronized
    fun setTxTail(units: Int) {
        require(units >= 0) { "txTailUnits must be >= 0 (got $units)." }
        modulator.setTxTail(units)
    }

    /**
     * Modulates a raw AX.25 UI frame (without CRC/FCS) into normalized mono float PCM samples
     * in `[-1.0f, 1.0f]`.
     *
     * @param ax25WithoutCrc The raw AX.25 UI frame bytes without CRC/FCS. From `AprsTx.encodePacket().ax25Bytes`.
     * @return A [FloatArray] containing the modulated audio samples in `[-1.0f, 1.0f]`.
     * @throws IllegalArgumentException if the input frame is empty or exceeds the maximum allowed size.
     * @Synchronized ensures thread safety when modulating, as `javAX25`'s internal state is not thread-safe.
     */
    @Synchronized
    fun modulateToFloat(ax25WithoutCrc: ByteArray): FloatArray {
        require(ax25WithoutCrc.isNotEmpty()) { "AX.25 frame must not be empty." }
        require(ax25WithoutCrc.size <= MAX_AX25_BYTES_WITHOUT_CRC) {
            "AX.25 frame exceeds max $MAX_AX25_BYTES_WITHOUT_CRC bytes without CRC (got ${ax25WithoutCrc.size})."
        }


        val packet = Packet(ax25WithoutCrc) // javAX25 appends the 2-byte CRC here
        modulator.prepareToTransmit(packet)

        // Read the modulated samples in chunks until the modulator indicates no more samples are available.
        // Each chunk generated by the modulator is stored in `out` which is the final FloatArray handed to AudioTrack for playback.
        val chunkBuf: FloatArray = modulator.txSamplesBuffer
        var out = FloatArray(sampleRate)
        var total = 0

        while (true) {
            val count = modulator.samples
            if (count <= 0) break
            if (total + count > out.size) {
                var newCapacity = out.size * 2
                while (newCapacity < total + count) {
                    newCapacity *= 2
                }
                out = out.copyOf(newCapacity)
            }
            System.arraycopy(chunkBuf, 0, out, total, count)
            total += count
        }

        return if (total == out.size) out else out.copyOf(total)
    }

    /** Modulates an [EncodedTxPacket] into normalized mono float PCM samples in `[-1.0f, 1.0f]`. */
    fun modulateToFloat(encoded: EncodedTxPacket): FloatArray =
        modulateToFloat(encoded.ax25Bytes)

    /** Modulates a raw AX.25 UI frame (without CRC/FCS) into signed 16-bit mono PCM ([ShortArray]).
     *
     * Result of this function can be directly fed into `AudioTrack.write()` for playback.
     * */
    fun modulateToPcm16(ax25WithoutCrc: ByteArray): ShortArray =
        floatToPcm16(modulateToFloat(ax25WithoutCrc))

    /** Modulates an [EncodedTxPacket] into signed 16-bit mono PCM ([ShortArray]). */
    fun modulateToPcm16(encoded: EncodedTxPacket): ShortArray =
        modulateToPcm16(encoded.ax25Bytes)
}


